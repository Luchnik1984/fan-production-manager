-- ============================================================================
-- V27__remove_motor_preset.sql
-- US10.6: удаление системного пресета «Электродвигатель AC».
--
-- Электродвигатель остаётся хардкод-типом: у него нет шаблона, поэтому
-- пресет полей к нему не применим и только путает администратора.
-- Пресеты колёс остаются — они нужны для перевода колёс на шаблоны (US10.7).
-- ============================================================================

DELETE
FROM field_preset
WHERE LOWER(name) = LOWER('Электродвигатель AC');
