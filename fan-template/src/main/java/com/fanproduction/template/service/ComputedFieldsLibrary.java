package com.fanproduction.template.service;

import java.util.Map;
import java.util.Set;

/**
 * Библиотека вычисляемых полей.
 * <p>
 * Вычисляемые поля определяются в коде (см. FR4.5.4) и регистрируются
 * при старте приложения. Они используются в правилах маркировки
 * для подстановки значений, которые вычисляются на основе других полей.
 * <p>
 * Все поля имеют строковый тип возврата — это соответствует тому, что
 * они используются в текстовой конкатенации маркировки.
 */
public interface ComputedFieldsLibrary {

    /**
     * Вычислить значение поля по имени.
     *
     * @param name   имя вычисляемого поля (например, {@code "voltageCode"})
     * @param values карта значений полей карточки
     * @return вычисленное значение или {@code null}, если поле
     *         не зарегистрировано или вычислить не удалось
     */
    String evaluate(String name, Map<String, Object> values);

    /**
     * Проверить, зарегистрировано ли поле с таким именем.
     */
    boolean isRegistered(String name);

    /**
     * Все зарегистрированные имена вычисляемых полей.
     */
    Set<String> getRegisteredNames();

    /**
     * Зарегистрировать новое вычисляемое поле.
     * <p>
     * Используется для расширения библиотеки (см. FR4.5.4 и NFR8.1).
     * Не перезаписывает уже зарегистрированное поле — для этого нужно
     * явно вызвать {@link #unregister(String)}.
     *
     * @throws IllegalArgumentException если поле с таким именем уже зарегистрировано
     */
    void register(String name, ComputedField field);

    /**
     * Удалить поле из библиотеки.
     * Возвращает {@code true}, если поле было зарегистрировано и удалено.
     */
    boolean unregister(String name);
}